/* ============================================================
   Assistant - high-level orchestration of JARVIS behavior.
   Maps user/AI intents to a state pipeline + widget reveals +
   simulated audio. Today driven by tap/hold and the debug
   "ASK" buttons; tomorrow by the AI/server.
   ============================================================ */
import { bus } from './EventBus.js';
