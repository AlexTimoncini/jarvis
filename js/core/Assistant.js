/** Topic -> widget that should appear when that topic is requested. */
export const TOPIC_WIDGET = {
  orario: 'clock',
  meteo: 'weather',
  sistema: 'stats',
  link: 'links',
  musica: 'wave',
};

/** Map a free-form spoken command to a widget to reveal. */
const COMMAND_PATTERNS = [
  { re: /(meteo|tempo|prevision|temperatur|piov)/i, widget: 'weather' },
  { re: /(ora|orari|che ore|data|giorno|adesso)/i, widget: 'clock' },
  { re: /(sistem|cpu|memori|stato|diagnos|potenz)/i, widget: 'stats' },
  { re: /(musica|canzon|brano|suona|playlist)/i, widget: 'wave' },
  { re: /(link|collegament|applicazion|\bapp\b)/i, widget: 'links' },
];

export function widgetForCommand(text = '') {
  for (const p of COMMAND_PATTERNS) if (p.re.test(text)) return p.widget;
  return null;
}

